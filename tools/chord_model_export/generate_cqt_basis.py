"""Write Sources/SongWorkbench/ChordNetCQTBasis.swift: librosa's constant-Q filter basis for the chord
network's features (librosa.cqt, sr 22050, hop 512, 288 bins at 36 per octave from F#0, tuning 0,
hann window, L1 norm, sparsity 0.01). At these settings every octave uses the same 36 x 257 basis
over a 512-point FFT at half the previous octave's sample rate (no early downsampling), so one
basis plus the 288 filter lengths reproduce librosa.cqt."""
import sys
import numpy as np
import librosa
from librosa import filters
from librosa.core import constantq

SR, BPO, N_BINS, HOP = 22050, 36, 288, 512
fmin = librosa.note_to_hz("F#0")
freqs = librosa.interval_frequencies(n_bins=N_BINS, fmin=fmin, intervals="equal", bins_per_octave=BPO, sort=True)
alpha = filters._relative_bandwidth(freqs=freqs)
lengths, _ = filters.wavelet_lengths(freqs=freqs, sr=SR, window="hann", filter_scale=1, gamma=0, alpha=alpha)
basis, n_fft, _ = constantq.__dict__["__vqt_filter_fft"](
    SR, freqs[-BPO:], 1, 1, 0.01, window="hann", gamma=0, dtype=np.complex64, alpha=alpha[-BPO:])
basis = basis.tocoo()
assert n_fft == 512
entries = sorted(zip(basis.row.tolist(), basis.col.tolist(), basis.data.tolist()))
out = [
    "// Generated by tools/chord_model_export/generate_cqt_basis.py from librosa "
    f"{librosa.__version__}. Do not edit by hand.",
    "",
    "extension ChordNetFeatures {",
    "    /// The top octave's constant-Q basis over a 512-point FFT: (bin within octave, FFT bin,",
    "    /// real, imaginary). Every lower octave reuses it at half the sample rate.",
    "    static let basis: [(row: Int, column: Int, real: Float, imaginary: Float)] = [",
]
for r, c, v in entries:
    out.append(f"        ({r}, {c}, {float(np.float32(v.real))!r}, {float(np.float32(v.imag))!r}),")
out += ["    ]", "", "    /// Each of the 288 filters' length in samples at 22,050 Hz, lowest first.",
        "    static let filterLengths: [Float] = ["]
for i in range(0, N_BINS, 4):
    out.append("        " + ", ".join(repr(float(np.float32(x))) for x in lengths[i:i + 4]) + ",")
out += ["    ]", "}", ""]
open(sys.argv[1], "w").write("\n".join(out))
print(len(entries), "basis entries,", N_BINS, "lengths")
